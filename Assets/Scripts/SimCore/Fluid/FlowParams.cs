namespace BlockField.SimCore.Fluid
{
    /// <summary>
    /// 流れ場のパラメータ (系列2 Phase B)。
    ///
    /// **世界法則の側だけを持つ。** 生物の戦略パラメータはここに置かない
    /// （置いた時点で「創発」の主張が無効になる。prototypes/README の設計原則）。
    ///
    /// 【物理単位で持つ】2026-08-16 の実機セッションで、粒子が
    /// 毎フレーム 20cm 飛んで流れに見えなかった。原因は ψ の振幅に
    /// 物理スケールを与えていなかったことで、流速がセルサイズに反比例していた
    /// （6.5cm で 7.72、5.5cm で 9.39）。セルサイズの比較が解像度の比較に
    /// なっていなかった。**目標流速と渦の大きさを m 単位で指定する形に変えた。**
    /// </summary>
    public struct FlowParams
    {
        /// <summary>ノイズのシード。3成分にはこれと +1、+2 を使う。</summary>
        public uint Seed;

        /// <summary>fBm のオクターブ数。3 が既定（roadmap の「カールノイズ3オクターブ」）。</summary>
        public int Octaves;

        /// <summary>
        /// **目標流速 (m/s)。** 水セルの流速の**中央値**がこの値になるよう正規化する。
        /// セルサイズを変えても同じ速さになる（正規化は実測に基づくため）。
        ///
        /// 目安:
        /// - 0.01〜0.05 … 水中の微粒子が漂う速さ。ただし 0.01 は
        ///   1フレーム 0.014cm で「動いているか分からない」恐れがある
        /// - **0.08** … 1フレーム 0.11cm。粒子径 1〜2cm の 1/10 程度で
        ///   仮現運動が確実に成立する（2026-08-16 に採用）
        /// - 0.3 … 1フレーム 0.42cm。やや速い
        /// </summary>
        public float TargetSpeed;

        /// <summary>
        /// 渦のおおよその直径 (m)。ノイズの波長。
        /// **セル数ではなくメートルで持つ**ので、セルサイズを変えても
        /// 流れの空間構造が変わらない。
        /// 実測では 0.5m 相当で「向きが反転するまで中央 71cm」だった。
        /// </summary>
        public float EddySizeMeters;

        /// <summary>
        /// 1ティックあたりノイズ模様が流れる距離 (m)。流れの「ゆっくりした変化」の速さ。
        /// これも m で持つのでセルサイズに依存しない。
        /// </summary>
        public float NoiseDriftPerTick;

        /// <summary>
        /// 境界のランプ幅（セル数）。**壁面**からこの距離まで ψ を滑らかに 0 へ落とす。
        ///
        /// 【壁面はセル中心ではない】固体セルと水セルの境目は、どちらの中心からも
        /// 0.5 セルの位置にある。距離場が 0 になるのは固体セルなので、
        /// 壁に接する最初の水セルの距離は 1.0 セル。ランプは
        /// **(d − 0.5) を入力に取る**（そうしないと壁際で ψ が残る。
        /// 修正前は smoothstep(1.0/2.5) = 0.35 も残っていて、
        /// 流れが壁を貫いていた: |u·n|/|u| = 0.227）。
        /// </summary>
        public float BoundaryRampCells;

        /// <summary>
        /// 浮力項の係数。**Phase D（温度センサ）まで 0**。
        /// 枠だけ用意しておくのは、後から入れるときに ψ の構成を変えずに済ませるため。
        ///
        /// 【アブレーション可能性】温度は「流れを作る」と「代謝を動かす」の2経路で効く。
        /// この2つを独立に無効化できる形にしておかないと、ある挙動が選ばれた理由が
        /// 流れなのか代謝なのか切り分けられなくなる（roadmap 系列2 §水流）。
        /// </summary>
        public float BuoyancyWeight;

        public static FlowParams Default => new FlowParams
        {
            Seed = 20260816u,
            Octaves = 3,
            TargetSpeed = 0.08f,
            EddySizeMeters = 0.5f,
            NoiseDriftPerTick = 0.004f,
            BoundaryRampCells = 2.5f,
            BuoyancyWeight = 0f,
        };
    }
}
